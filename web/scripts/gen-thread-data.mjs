const v2 = tt.configs.version2;
const v3 = tt.configs.version3;
const res = (r) => [r.weightedLength, r.valid, r.permillage, r.validRangeEnd];
const cases = [...corpus].map((text) => ({
  text,
  v3: res(tt.parseTweet(text, v3)),
  v2: res(tt.parseTweet(text, v2)),
  urls: tt.extractUrlsWithIndices(text).map((u) => [u.indices[0], u.indices[1], u.url.length]),
}));

// 이모지 표: 기호·그림 문자 범위의 모든 코드 포인트에 대해 단독·FE0F·FE0E·피부색이 붙었을 때 첫 이모지의 길이(UTF-16)
const ranges = [
  [0x23, 0x23],
  [0x2a, 0x2a],
  [0x30, 0x39],
  [0xa9, 0xa9],
  [0xae, 0xae],
  [0x2000, 0x2bff],
  [0x3030, 0x3030],
  [0x303d, 0x303d],
  [0x3297, 0x3299],
  [0xe50a, 0xe50a],
  [0x1f000, 0x1faff],
];
const first = (s) => {
  const e = parseEmoji(s);
  return e.length && e[0].indices[0] === 0 ? e[0].indices[1] : 0;
};
const emoji = [];
for (const [a, b] of ranges) {
  for (let cp = a; cp <= b; cp++) {
    const ch = String.fromCodePoint(cp);
    const row = [cp, first(ch), first(ch + '️'), first(ch + '︎'), first(ch + '\u{1f3fd}'), first(ch + '️⃣')];
    if (row.slice(1).some((x) => x)) emoji.push(row);
  }
}

