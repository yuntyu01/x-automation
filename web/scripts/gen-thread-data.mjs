const { parse: parseEmoji } = require('twemoji-parser');
const ttVersion = require('twitter-text/package.json').version;
const emojiVersion = require('twemoji-parser/package.json').version;

// URL 정규식은 조각으로 내보낸다. Go는 표준 regexp(RE2, 선형 시간)로 같은 구조를 다시 조립하고,
// RE2에 없는 TLD 뒤 lookahead만 같은 우선순위의 대안으로 바꾼다 (internal/thread/twittertext.go).
const sources = {
  validURLPrecedingChars: re('validUrlPrecedingChars'),
  validSubdomain: re('validSubdomain'),
  validDomainName: re('validDomainName'),
  validGTLD: re('validGTLD'),
  validCCTLD: re('validCCTLD'),
  validPunycode: re('validPunycode'),
  validPortNumber: re('validPortNumber'),
  validURLPath: re('validUrlPath'),
  validURLQueryChars: re('validUrlQueryChars'),
  validURLQueryEndingChars: re('validUrlQueryEndingChars'),
  validASCIIDomain: re('validAsciiDomain'),
  validTcoURL: re('validTcoUrl'),
  invalidURLWithoutProtocolPrecedingChars: re('invalidUrlWithoutProtocolPrecedingChars'),
  invalidChars: re('invalidChars'),
  emoji: emojiRe,
};

// 조각이 라이브러리의 실제 정규식 구조와 같은지 확인한다 (라이브러리가 바뀌면 여기서 멈춘다)
{
  const s = Object.fromEntries(Object.entries(sources).map(([k, v]) => [k, v.source]));
  const domain = `(?:${s.validSubdomain}*${s.validDomainName}(?:${s.validGTLD}|${s.validCCTLD}|${s.validPunycode}))`;
  if (re('validDomain').source !== domain) throw new Error('validDomain 구조가 예상과 달라요');
  const extract = `((${s.validURLPrecedingChars})((https?:\\/\\/)?(${domain})(?::(${s.validPortNumber}))?(\\/${s.validURLPath}*)?(\\?${s.validURLQueryChars}*${s.validURLQueryEndingChars})?))`;
  if (re('extractUrl').source !== extract) throw new Error('extractUrl 구조가 예상과 달라요');
  if (re('extractUrl').flags !== 'gi' || re('validAsciiDomain').flags !== 'gi') throw new Error('플래그가 예상과 달라요');
}

const lit = (s) => {
  const j = JSON.stringify(s);
  if (/\\u[dD][89abAB]/.test(j.replace(/\\\\/g, ''))) throw new Error('lone surrogate escape in Go literal');
  return j;
};

let go = `// Code generated by web/scripts/gen-thread-data.mjs; DO NOT EDIT.
// 원본: twitter-text ${ttVersion}, twemoji-parser ${emojiVersion} (Apache-2.0 / MIT)

package thread

// 정규식 원문은 JavaScript 문법 그대로다. Go에서는 regexp2(ECMAScript 모드)로 UTF-16 코드 단위 위에서 실행해
// 공식 라이브러리와 같은 위치·결과를 얻는다.
const (
`;
for (const [name, rx] of Object.entries(sources)) {
  go += `\tsrc${name[0].toUpperCase()}${name.slice(1)} = ${lit(rx.source)}\n`;
  go += `\tflags${name[0].toUpperCase()}${name.slice(1)} = ${lit(rx.flags)}\n`;
}
go += `)\n\n// 가중치 설정 (twitter-text configs)\nvar (\n`;
for (const [name, key] of [
  ['V2', 'version2'],
  ['V3', 'version3'],
]) {
  const c = tt.configs[key];
  go += `\t${name} = Config{MaxWeighted: ${c.maxWeightedTweetLength}, Scale: ${c.scale}, DefaultWeight: ${c.defaultWeight}, URLLength: ${c.transformedURLLength}, EmojiParsing: ${!!c.emojiParsingEnabled},\n\t\tRanges: []weightRange{${c.ranges.map((r) => `{${r.start}, ${r.end}, ${r.weight}}`).join(', ')}}}\n`;
}
go += `)\n`;
writeFileSync(join(root, 'internal/thread/twittertext_gen.go'), go);
try {
  execFileSync('gofmt', ['-w', join(root, 'internal/thread/twittertext_gen.go')]);
} catch {
  console.warn('gofmt를 찾지 못했어요. make lint 전에 gofmt -w internal/thread/twittertext_gen.go를 실행하세요');
}

// ── 기대값 ────────────────────────────────────────────────────────────
