// 공식 twitter-text(프론트가 쓰는 라이브러리)에서 Go 서버용 규칙과 기대값을 만든다.
//
//   node scripts/gen-thread-data.mjs   (npm run gen:thread)
//
// 만드는 파일
//   - internal/thread/twittertext_gen.go: URL·이모지·금지 문자 정규식 원문과 가중치 설정 (Go가 같은 정규식을 UTF-16 단위로 실행)
//   - testdata/thread/golden.json: 같은 라이브러리로 계산한 가중 길이·URL 위치 기대값 (Go·Vitest가 함께 대조)
//
// 라이브러리 버전을 올리면 이 스크립트를 다시 돌리고 make test로 두 구현이 같은지 확인한다.
import { execFileSync } from 'node:child_process';
